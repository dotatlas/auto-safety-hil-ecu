"""Generate the C codecs in firmware/generated from the DBC file."""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DBC = REPO / "can" / "vehicle_hil.dbc"
OUTPUT = REPO / "firmware" / "generated"
TIMESTAMP = re.compile(r"(generated by cantools version \S+) .*")


def generate(output: Path) -> None:
    """Run the cantools C generator on the DBC. Called by main and by the up-to-date test."""
    output.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, "-m", "cantools", "generate_c_source", str(DBC), "-o", str(output)]
    subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
    # cantools writes the time in each file. Remove it, so the same DBC gives the same files.
    for path in output.glob("vehicle_hil.*"):
        path.write_text(TIMESTAMP.sub(r"\1", path.read_text()), newline="\n")


def main() -> None:
    """Parse the output folder argument and call generate."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    generate(parser.parse_args().output)


if __name__ == "__main__":
    main()
